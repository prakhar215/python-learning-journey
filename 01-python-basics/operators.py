
a = 10
b = 3

# 1. Arithmetic Operators
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)

# 2. Comparison Operators
print("Equal:", a == b)
print("Greater than:", a > b)
print("Less than:", a < b)

# 3. Logical Operators
print("AND:", a > 5 and b < 5)
print("OR:", a < 5 or b < 5)
print("NOT:", not(a > b))

# 4. Assignment Operator
a += 5
print("Updated a:", a)
